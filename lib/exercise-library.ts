/**
 * THE EXERCISE LIBRARY, AS RECORDS.
 *
 * One record per exercise in docs/EXERCISE-LIBRARY.md, which is the source of
 * truth Archie supplied. tests/exercise-library.check.mjs parses that document
 * at run time and compares it against this file, so the two cannot drift: add a
 * row to the document without adding a record here and the check fails, and the
 * other way round.
 *
 * NOTHING IMPORTS THIS FILE YET. It is built beside the existing engine and
 * wired up later, one session type at a time.
 *
 * WHY THESE EXTEND ExerciseTemplate
 * ─────────────────────────────────
 * Progression, set logging and the session screen already know how to read an
 * ExerciseTemplate. A library record IS one, with four extra facts the document
 * gives us: the pattern it belongs to, the level it starts at, the kit it needs
 * and the job it does in a session. Nothing downstream has to learn a new shape.
 *
 * WHY SOME IDS LOOK NOTHING LIKE THE OTHERS
 * ─────────────────────────────────────────
 * Every load, every rep count and every progression a person has ever logged is
 * filed under the id of the exercise they did. So where a record is the same
 * movement done with the same implement as an exercise the app already has, the
 * record keeps that exercise's id and the person's history carries straight
 * over. 89 of the 160 records do. The rest are movements the app has never had,
 * or a genuinely different variant of one it has (a deficit, a pause, a band, a
 * different bar), and those get a fresh `lib-<pattern>-<name>` id, because
 * serving somebody their barbell deadlift weight on a snatch-grip deficit
 * deadlift would be worse than starting them fresh.
 *
 * Which is which was settled from the approved scope document: its "exact
 * match" and "same movement and kit, only a rename or a re-file is needed"
 * lists keep their ids; its "different kit, missing modifier or different
 * variant" list and its "no template at all" list get new ones. Two deliberate
 * departures from that rule, both written down so they can be argued with:
 *
 *   - Kettlebell Goblet Squats keeps sq-main-db (Goblet Squat). The scope
 *     document calls it a different variant because the existing template is
 *     cued with a dumbbell, but decision 5 says a dumbbell may stand in for a
 *     kettlebell on exactly this exercise, so by the owner's own ruling it is
 *     the same implement. It is also a main lift, so the loads people have
 *     logged against it are the ones worth keeping.
 *   - Box Step Downs does NOT keep ph-r-kn-2 (Slow Step-Down), which the scope
 *     document offers as its stand-in. That template is Restore content, and
 *     Restore is explicitly not governed by this list, so it keeps serving
 *     under its own name. One id cannot be two exercises with two names.
 *
 * Several of the reused ids have duplicates elsewhere in the catalogue (the
 * same movement filed again under another equipment tier). Those are merged in
 * a later phase, which copies progress forward onto the surviving id; nothing
 * here has to choose between them beyond picking the survivor.
 *
 * WHY movementPattern IS STILL HERE ALONGSIDE pattern
 * ───────────────────────────────────────────────────
 * They answer different questions. `pattern` is the library's own filing: one
 * of the six the document uses, and the thing a session slot asks for.
 * `movementPattern` is the older, finer description that loaded-hinge
 * detection, swap suggestions and session diversity all read. A carry and a
 * plank are both `core` to the library and are not the same movement at all.
 *
 * CONTENT IS AUTHORED FOR THE 122 RECORDS THAT HAD A TEMPLATE TO START FROM
 * ────────────────────────────────────────────────────────────────────────
 * Sets, reps, cue, load, muscles, regions, video and stress tags are written
 * out on every record the app already had in some form: the scope document's
 * exact matches, its "only a rename is needed" matches, and its "the nearest
 * template uses different kit or lacks the modifier" matches, plus all nine
 * conditioning exercises. Each was seeded from the template it matched and then
 * corrected where that template described the wrong implement: Kettlebell
 * Goblet Squats is cued with a bell rather than a dumbbell, Barbell Jump Squats
 * takes the barbell jump-squat video that was sitting on a dumbbell template,
 * and the kettlebell carries are cued as kettlebells.
 *
 * The 38 records with no template behind them at all still spread
 * PLACEHOLDER_CONTENT and are written in the next step, from drafts the owner
 * has approved. `hasAuthoredContent` is how anything tells the two apart, and
 * nothing may serve a record that has not been written yet.
 *
 * REPS ARE A DOSE THE APP EITHER COUNTS OR REFUSES TO
 * ───────────────────────────────────────────────────
 * `dose` says which. 'reps' is a countable prescription and parseReps must read
 * it, because that is what double progression climbs. 'time', 'distance' and
 * 'quality' are the three kinds of dose that must NOT be progressed by adding
 * reps, and parseReps must refuse all three:
 *
 *   - 'time' and 'distance' are decision 9. A plank, a wall sit and a carry get
 *     a fixed hold or a fixed walk chosen for the level they sit at, and the
 *     way they get harder is more weight, not more seconds. Progressing them by
 *     reps is the bug parseReps was written to prevent: a 40 m farmer's carry
 *     came back as "8-12 m".
 *   - 'quality' is the jumps, throws and slams. Nobody adds reps to a depth
 *     jump. The set ends when the speed does.
 *
 *
 * `equipmentRequired` IS A HOLDING ANSWER
 * ───────────────────────────────────────
 * `kit` is the real one, and the next step teaches the equipment gate to read
 * it. Until then every record says 'bodyweight' if it needs nothing and
 * 'fullgym' if it needs anything at all, because that is the direction of error
 * that costs nobody a session: an exercise hidden from somebody who could have
 * done it, rather than offered to somebody who cannot.
 */

/** The six movement patterns the library files everything under. */
export type LibraryPattern = 'push' | 'pull' | 'hinge' | 'squat' | 'lunge' | 'core';

/** Beginner 1, Intermediate 2, Advanced 3, Athlete 4 — the onboarding answers. */
export type LibraryLevel = 1 | 2 | 3 | 4;

/** The onboarding wording for each level, for anything that shows it. */
export const LIBRARY_LEVEL_NAMES: Record<LibraryLevel, string> = {
  1: 'Beginner',
  2: 'Intermediate',
  3: 'Advanced',
  4: 'Athlete',
};

/**
 * Every named piece of kit in the library, as one short key each.
 *
 * "Weight Plates" and "Weight Plate" are both `plates`; a block and a plate are
 * interchangeable wherever the document offers the choice, so they stay two
 * keys and the record asks for either.
 */
export const KIT_KEYS = [
  'plates',
  'blocks',
  'bench',
  'box',
  'band',
  'dumbbell',
  'kettlebell',
  'barbell',
  'landmine',
  'corner',
  'rack',
  'trx',
  'medball',
  'slamball',
  'cable',
  'latpulldown',
  'pullupbar',
  'trapbar',
  'abwheel',
  'doorframe',
  'sled',
  'assaultbike',
  'treadmill',
  'rower',
  'rope',
] as const;

export type KitKey = (typeof KIT_KEYS)[number];

/**
 * What an exercise needs, as an AND of ORs.
 *
 * Each inner list is one requirement that any of its keys satisfies, and every
 * requirement has to be met. So a Landmine Press is
 * `[['barbell'], ['landmine', 'corner']]`: you need the bar, and you need
 * either the attachment or a corner to wedge it into. An empty list means the
 * exercise needs nothing at all, which is how the document's "Bodyweight" reads.
 */
export type KitRequirement = readonly (readonly KitKey[])[];

/**
 * What job the exercise does in a session.
 *
 * `main` leads a pattern slot and carries the load; `accessory` supports it;
 * `power` is the jumps, throws and slams, which the document keeps at Athlete
 * level only (decision 8) and which fill the power block rather than a pattern
 * slot.
 */
export type LibraryRole = 'main' | 'accessory' | 'power';

/**
 * What kind of dose the `reps` field holds. See the header for why it matters.
 *
 * 'reps' is the only one double progression may touch. The other three are
 * prescriptions parseReps has to refuse, and tests/library-clinical.check.mjs
 * holds every record to that both ways round.
 */
export type LibraryDose = 'reps' | 'time' | 'distance' | 'quality';

/**
 * Decision 9: a hold gets a fixed number of seconds, chosen for its level.
 *
 * Two ladders, because a plank and a loaded suitcase hold are not the same
 * exercise with different scenery. You can hold your own bodyweight in a
 * straight line for a long time; you cannot hold a loaded barbell in one hand
 * for anything like as long, and asking for it just means the bar gets lighter
 * until the number is reachable, which is the opposite of progress.
 */
export const HOLD_SECONDS_BY_LEVEL: Record<'bodyweight' | 'loaded', Record<LibraryLevel, number>> =
  {
    bodyweight: { 1: 30, 2: 40, 3: 45, 4: 60 },
    loaded: { 1: 20, 2: 30, 3: 40, 4: 45 },
  };

/**
 * Decision 9 again: a carry gets a fixed distance, chosen for its level.
 *
 * Athlete repeats Advanced on purpose. Past about forty metres a carry stops
 * being trunk and grip work and turns into conditioning, so the step up at the
 * top of the ladder is load, not distance.
 */
export const CARRY_METRES_BY_LEVEL: Record<LibraryLevel, number> = { 1: 20, 2: 30, 3: 40, 4: 40 };

export interface LibraryExercise extends ExerciseTemplate {
  /** The name exactly as docs/EXERCISE-LIBRARY.md spells it. */
  libraryName: string;
  pattern: LibraryPattern;
  /**
   * The second pattern this exercise is also listed under.
   *
   * Used once. The document lists "Squat Jump" under Squat and "Squat Jumps"
   * under Lunge, and says in its own notes that they are the same movement. One
   * record, both patterns, so a Lunge slot can still reach it and a person who
   * meets it in both never sees it twice under two names.
   */
  alsoPattern?: LibraryPattern;
  /** The spelling the document uses for the second listing. */
  alsoLibraryName?: string;
  level: LibraryLevel;
  kit: KitRequirement;
  role: LibraryRole;
  /** Absent until the record's content is written. See `hasAuthoredContent`. */
  dose?: LibraryDose;
  /**
   * What this movement asks of the body, written down rather than read off the
   * name.
   *
   * The screen recognises a movement from its name, which works until somebody
   * renames one. `stressTagsForRecord` screens on the UNION of this list and
   * the name rules, so a record can only ever be MORE protected than its name,
   * never less, and tests/library-clinical.check.mjs holds this list to being a
   * superset of what the name says so it cannot quietly go stale.
   */
  stress?: readonly StressTag[];
}

export interface ConditioningExercise extends ExerciseTemplate {
  libraryName: string;
  kit: KitRequirement;
  /**
   * Kit that makes the exercise better but is not needed to do it.
   *
   * Skipping only. Decision 7 says it is with a rope or on the spot, so a rope
   * can never be a reason to withhold it.
   */
  optionalKit?: readonly KitKey[];
  role: 'conditioning';
  /** Absent until the record's content is written. See `hasAuthoredContent`. */
  dose?: LibraryDose;
  /** As on a movement record. Never a level ladder: conditioning has no level. */
  stress?: readonly StressTag[];
}

/**
 * Stand-in content for the 38 records the app has never had in any form.
 *
 * Their prescriptions are written in the next step, from drafts the owner has
 * approved. Until then `hasAuthoredContent` returns false for them and nothing
 * may put one in a session.
 *
 * A function, not a shared object, so no two records end up pointing at the
 * same targetRegions array.
 */
const PLACEHOLDER_CONTENT = (): Pick<
  ExerciseTemplate,
  'sets' | 'reps' | 'cue' | 'suggestedLoad' | 'targetRegions' | 'videoId'
> => ({
  sets: 3,
  reps: '',
  cue: '',
  suggestedLoad: '',
  targetRegions: [] as PainRegion[],
  videoId: '',
});

/**
 * True once a record's prescription has actually been written.
 *
 * Read off the cue, because a cue is the one field a record cannot usefully be
 * served without: a card with no coaching line on it is the app admitting it
 * has nothing to say about the exercise it just asked you to do.
 */
export function hasAuthoredContent(exercise: LibraryExercise | ConditioningExercise): boolean {
  return exercise.cue.length > 0;
}

/** Every record whose prescription is written, movement and conditioning alike. */
export function authoredLibraryRecords(): (LibraryExercise | ConditioningExercise)[] {
  return [...LIBRARY_EXERCISES, ...CONDITIONING_EXERCISES].filter(hasAuthoredContent);
}

/**
 * Written records with no footage yet, which decision 15 allows.
 *
 * Asked through `videoUrlFor` rather than by reading `videoId`, because that is
 * the question the session screen asks: a record whose name happens to match
 * the table in lib/exercise-videos.ts has a video whether or not it carries an
 * id of its own.
 */
export function recordsWithoutVideo(): (LibraryExercise | ConditioningExercise)[] {
  return authoredLibraryRecords().filter((e) => !videoUrlFor(e));
}

/** Both patterns an exercise is filed under, which is two for exactly one of them. */
export function patternsOf(exercise: LibraryExercise): LibraryPattern[] {
  return exercise.alsoPattern ? [exercise.pattern, exercise.alsoPattern] : [exercise.pattern];
}

/** Every spelling the document uses for an exercise. */
export function libraryNamesOf(exercise: LibraryExercise): string[] {
  return exercise.alsoLibraryName
    ? [exercise.libraryName, exercise.alsoLibraryName]
    : [exercise.libraryName];
}

/** The records filed under a pattern, including the one filed under two. */
export function libraryByPattern(pattern: LibraryPattern): LibraryExercise[] {
  return LIBRARY_EXERCISES.filter((e) => patternsOf(e).includes(pattern));
}

